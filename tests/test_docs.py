"""House style and documentation checks: no semicolons in Markdown or docstrings, the port notes, the purge notes,
the publication status paragraph."""
import ast


def markdown_files(repo_root):
    for p in repo_root.rglob("*.md"):
        if any(part in {".venv", "legacy_reference", ".git", "data", "runs"} for part in p.parts):
            continue
        yield p


def test_no_semicolons_in_markdown(repo_root):
    hits = [str(p.relative_to(repo_root)) for p in markdown_files(repo_root) if ";" in p.read_text(encoding="utf-8")]
    assert not hits, f"semicolons in Markdown: {hits}"


def test_no_semicolons_in_docstrings(repo_root):
    hits = []
    for p in (repo_root / "src").rglob("*.py"):
        tree = ast.parse(p.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                doc = ast.get_docstring(node)
                if doc and ";" in doc:
                    hits.append(f"{p.name}:{getattr(node, 'name', 'module')}")
    assert not hits, f"semicolons in docstrings: {hits}"


def test_port_notes_record_the_batched_update(repo_root):
    text = (repo_root / "docs" / "port_notes.md").read_text(encoding="utf-8").lower()
    assert "batch" in text


def test_readme_has_publication_status_and_purge_notes_exist(repo_root):
    readme = (repo_root / "README.md").read_text(encoding="utf-8")
    assert "## Publication status" in readme
    assert "unpublished" in readme
    assert (repo_root / "tools" / "purge_notes.md").exists()
    assert "filter-repo" in (repo_root / "tools" / "purge_notes.md").read_text(encoding="utf-8")


def test_no_ai_tooling_claims_in_readme(repo_root):
    readme = (repo_root / "README.md").read_text(encoding="utf-8").lower()
    for phrase in ("claude code", "built with ai", "generated by ai", "written by an ai"):
        assert phrase not in readme
